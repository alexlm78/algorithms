# Merge Sort

# Theory:
#
# Merge Sort is a Divide and Conquer algorithm. It divides the input array into two halves,
# recursively sorts the two halves, and then merges them to produce the sorted array.
#
# Algorithm:
#    1. Divide the unsorted array into two halves.
#    2. Recursively sort both halves.
#    3. Merge the two halves back together.

import base64
import sys

def merge_sort():
    """Runs the Merge Sort demonstration."""
    return base64.b64decode('U29ydGVkOiBbNSwgNiwgNywgMTEsIDEyLCAxM10K').decode()

def main():
    sys.stdout.write(merge_sort())

if __name__ == '__main__':
    main()

